export function getLocalizedArmorSetName(setName: string): string | null {
  if (!setName) return null;
  if (currentLanguage === 'en') return null;
  const langSets = ARMOR_SET_TRANSLATIONS[currentLanguage];
  if (!langSets) return null;
  const lower = setName.toLowerCase().trim();
  return langSets[lower] || null;
}




export function localizeElements(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n!); });
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach(el => { safeSetInnerHTML(el, t(el.dataset.i18nHtml!)); });
  for (const attribute of ['title', 'placeholder', 'aria-label', 'alt']) {
    root.querySelectorAll<HTMLElement>(`[data-i18n-${attribute}]`).forEach(el => {
      el.setAttribute(attribute, t(el.getAttribute(`data-i18n-${attribute}`)!));
    });
  }
}
