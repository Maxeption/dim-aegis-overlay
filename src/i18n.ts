export function getLocalizedElement(energy: string): string {
  if (!energy) return '';
  const lower = energy.toLowerCase().trim();
  return t(lower) || energy;
}

export function getLocalizedFrame(frame: string): string {
  if (!frame) return '';
  const lower = frame.toLowerCase().trim().replace(/\s+frame$/i, '');
  const langFrames = FRAME_TRANSLATIONS[currentLanguage];
  if (langFrames && langFrames[lower]) {
    return langFrames[lower];
  }
  return frame;
}

export function getLocalizedCategory(cat: string): string {
  if (!cat) return '';
  let lower = cat.toLowerCase().trim();
  if (CATEGORY_ALIASES[lower]) {
    lower = CATEGORY_ALIASES[lower];
  }
  const langCats = CATEGORY_TRANSLATIONS[currentLanguage];
  if (langCats && langCats[lower]) {
    return langCats[lower];
  }
  return cat;
}

export function getLocalizedArchetypeLabel(labelStr: string): string {
  if (!labelStr) return '';
  const parts = labelStr.split(' / ');
  return parts.map(part => {
    const tokens = part.trim().split(/\s+/);
    return tokens.map(token => {
      const el = getLocalizedElement(token);
      if (el && el.toLowerCase() !== token.toLowerCase()) return el;
      const fr = getLocalizedFrame(token);
      if (fr && fr.toLowerCase() !== token.toLowerCase()) return fr;
      return token;
    }).join(' ');
  }).join(' / ');
}
